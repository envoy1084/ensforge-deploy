import type { Config } from "vocs/config";

interface SidebarItem {
  collapsed?: boolean;
  items?: SidebarItem[];
  link?: string;
  text?: string;
}

const slug = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const title = (value: string) => {
  const moduleName = value.split("/").at(-1) ?? value;
  return moduleName
    .split("-")
    .map(
      (part) =>
        ({
          dns: "DNS",
          dnssec: "DNSSEC",
          ens: "ENS",
          erc: "ERC",
          eth: "ETH",
          hca: "HCA",
          l2: "L2",
          v1: "V1",
          v2: "V2",
        })[part] ?? part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join(" ");
};

const apiGroup = (base: string, text: string, names: ReadonlyArray<string>): SidebarItem => ({
  collapsed: true,
  items: names.map((name) => ({ link: `${base}/${slug(name)}`, text: name })),
  text,
});

const contractGroup = (text: string, modules: ReadonlyArray<string>): SidebarItem => ({
  collapsed: true,
  items: modules.map((module) => ({ link: `/contracts/api/${module}`, text: title(module) })),
  text,
});

const apiSectionsGroup = (
  base: string,
  text: string,
  groups: ReadonlyArray<{
    readonly path: string;
    readonly text: string;
    readonly names: ReadonlyArray<string>;
  }>,
): SidebarItem => ({
  collapsed: true,
  items: groups.flatMap((group) =>
    group.names.map((name) => ({
      link: `${base}${group.path}/${slug(name)}`,
      text: name,
    })),
  ),
  text,
});

